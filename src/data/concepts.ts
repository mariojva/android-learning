export const CONCEPT_MAP = new Map(CONCEPTS.map((c) => [c.id, c]));

export function conceptsForModule(moduleId: string): Concept[] {
  return CONCEPTS.filter((c) => c.moduleId === moduleId);
}

/** Concepts that list `id` as a prerequisite — the outgoing edges. */
export function unlockedBy(id: string): Concept[] {
  return CONCEPTS.filter((c) => c.prerequisites?.includes(id));
}
